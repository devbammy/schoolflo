const readablePassword = () => {
  const bytes = crypto.randomBytes(2);
  const digits = String(crypto.randomInt(0, 100)).padStart(2, '0');
  return `${WORDS[bytes[0]]}-${WORDS[bytes[1]]}-${digits}`;
};

